package com.opeartor;
//Assignment Operators
// = += -= *= /= %=
public class Arthimeticopertors {

	public static void main(String[] args) {
		int result=5;
		 result=(int) (result+4.5);
		 
		 System.out.println("Result is :"+ result);
		 
		 result+=4.5;
		 System.out.println("Result is :"+ result);
		 
		 result-=4.5;
		 System.out.println("Result is :"+ result);
		 
		 result*=4.5;
		 System.out.println("Result is :"+ result);
		 result/=4.5;
		 System.out.println("Result is :"+ result);
		 result%=4.5;
		 System.out.println("Result is :"+ result);
		 
		 
		 

	}

}
