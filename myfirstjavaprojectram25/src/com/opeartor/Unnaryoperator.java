package com.opeartor;
//unnary operator 
// +a -b ++a --b 
public class Unnaryoperator {
	

	public static void main(String[] args) {
		
		int a=5;
		int b=8;
	System.out.println(+a);
	System.out.println(-b);
	System.out.println(++a);
	System.out.println(--b);
	System.out.println(++a);
	System.out.println(--b);
	System.out.println(++a);
	System.out.println(--b);
	}
}
